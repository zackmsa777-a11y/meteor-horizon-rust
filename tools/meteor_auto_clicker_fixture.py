"""Real AutoClicker input/use tests in caller-owned fresh singleplayer world."""

def run_auto_clicker(ctl, check, state, scratch, report, x, y, z):
    ctl('release')
    if ctl('state')['meteor']['gui']['open']:
        ctl('key', 'rshift', 'tap')
    for module in ctl('state')['meteor']['config']['modules']['modules']:
        if module['active']:
            ctl('command', 'meteor toggle ' + module['id'])
    ctl('command', 'gamemode survival')
    ctl('command', 'clear @s')
    ctl('command', 'effect clear @s')
    ctl('command', f'fill {x-4} {y-1} {z-4} {x+4} {y-1} {z+8} minecraft:stone')
    ctl('command', f'fill {x-4} {y} {z-4} {x+4} {y+5} {z+8} minecraft:air')
    ctl('tp', x+0.5, y, z+0.5)
    ctl('look', 0, -70)
    ctl('hotbar', 1)
    ctl('command', 'meteor set auto-clicker mode-left Disabled')
    def refill():
        ctl('command', 'item replace entity @s weapon.mainhand with minecraft:experience_bottle 64')
        ctl('wait', 5)
    def remaining():
        return ctl('inventory')['counts'].get('minecraft:experience_bottle', 0)
    refill()
    ctl('wait', 15)
    check('Disabled AutoClicker does not use actual items', remaining() == 64)
    ctl('command', 'meteor set auto-clicker mode-right Press')
    ctl('command', 'meteor set auto-clicker delay-right 2')
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 18)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 2)  # Source permits its already queued right click after disable.
    ordinary = 64 - remaining()
    check('AutoClicker Press consumes real server items', ordinary > 0, ordinary)
    frozen = remaining()
    ctl('wait', 10)
    check('Disabling AutoClicker stops after queued source click', remaining() == frozen)
    refill()
    ctl('command', 'meteor set auto-clicker delay-right 0')
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 18)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 2)
    fast = 64 - remaining()
    check('Zero-delay Press exceeds source delay-two cadence', fast > ordinary, {'delay2':ordinary,'delay0':fast})
    refill()
    ctl('command', 'meteor set auto-clicker mode-right Hold')
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 18)
    held = 64 - remaining()
    check('AutoClicker Hold follows actual vanilla use cooldown', 0 < held < fast, {'hold':held,'press0':fast})
    held_before = remaining()
    ctl('command', 'meteor set auto-clicker mode-right Disabled')
    ctl('wait', 10)
    check('Changing Hold to Disabled preserves source held-key state', remaining() < held_before)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 2)
    # Direct Press works in screens by default; disabled screen setting pauses it.
    refill()
    ctl('command', 'meteor set auto-clicker mode-right Press')
    ctl('command', 'meteor set auto-clicker while-in-screens false')
    ctl('key', 'e', 'tap')
    ctl('wait', 2)
    check('AutoClicker screen fixture opens real inventory', ctl('state')['screen'] != 'playing')
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 10)
    check('AutoClicker screen filter prevents actual item use', remaining() == 64)
    ctl('command', 'meteor set auto-clicker while-in-screens true')
    ctl('wait', 10)
    check('AutoClicker enabled screen mode uses actual server item', remaining() < 64)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('key', 'escape', 'tap')
    ctl('wait', 3)
    # Hold mines a real survival block without a synthetic held mouse input.
    ctl('command', 'meteor set auto-clicker mode-right Disabled')
    ctl('command', 'meteor set auto-clicker mode-left Hold')
    ctl('command', 'item replace entity @s weapon.mainhand with minecraft:iron_pickaxe')
    ctl('command', f'setblock {x} {y+1} {z+2} minecraft:stone')
    ctl('tp', x+0.5, y, z+0.5)
    ctl('look', 0, 0)
    ctl('wait', 4)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 30)
    ctl('command', 'meteor toggle auto-clicker')
    ctl('wait', 3)
    blocks = ctl('blocks', x,y+1,z+2,x,y+1,z+2)['blocks']
    check('AutoClicker left Hold mines actual survival stone', not blocks, blocks)
    ctl('command', f'setblock {x} {y+1} {z+2} minecraft:stone')
    ctl('wait', 30)
    check('Disabling AutoClicker releases held attack', bool(ctl('blocks',x,y+1,z+2,x,y+1,z+2)['blocks']))
    state('auto_clicker_complete')
